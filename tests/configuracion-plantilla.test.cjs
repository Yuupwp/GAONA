const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
test('npm run web:configurar crea .env en instalación aislada y conserva una configuración existente', t => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gaona-configuracion-'));
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
    fs.mkdirSync(path.join(dir, 'api/scripts'), { recursive: true });
    for (const file of ['package.json', '.gitignore', 'api/.env.example', 'api/scripts/entorno-compartido.cjs']) fs.copyFileSync(path.join(root, file), path.join(dir, file));
    const ejecutar = () => spawnSync('npm', ['run', 'web:configurar'], { cwd: dir, encoding: 'utf8', env: { PATH: process.env.PATH } });
    const primero = ejecutar();
    assert.equal(primero.status, 0, primero.stderr);
    const archivo = path.join(dir, 'api/.env');
    assert.deepEqual(fs.readFileSync(archivo), fs.readFileSync(path.join(root, 'api/.env.example')));
    assert.equal(fs.statSync(archivo).mode & 0o777, 0o600);
    fs.writeFileSync(archivo, '# configuración privada existente\nJWT_SECRET=no-sobrescribir\n');
    const antes = fs.readFileSync(archivo);
    const segundo = ejecutar();
    assert.notEqual(segundo.status, 0);
    assert.match(segundo.stderr, /WEB_EXISTE/);
    assert.deepEqual(fs.readFileSync(archivo), antes);
    assert.equal(spawnSync('git', ['init', '-q', dir]).status, 0);
    const ignore = file => spawnSync('git', ['-C', dir, '-c', 'core.excludesFile=/dev/null', 'check-ignore', '-q', '--no-index', file]).status;
    assert.equal(ignore('api/.env'), 0);
    assert.equal(ignore('api/.env.example'), 1);
});
